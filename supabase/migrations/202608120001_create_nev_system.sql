create or replace function nev_private.nev_is_active_staff()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.nev_profiles
    where user_id = auth.uid() and active = true
  );
$$;

create or replace function nev_private.nev_is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.nev_profiles
    where user_id = auth.uid() and active = true and role = 'admin'
  );
$$;

create or replace function public.nev_claim_access(p_bootstrap_token text default null)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_email text;
  v_full_name text;
  v_has_profiles boolean;
  v_expected_hash text;
begin
  if v_user_id is null then
    raise exception 'É necessário entrar na conta.';
  end if;

  if exists (select 1 from public.nev_profiles where user_id = v_user_id) then
    return;
  end if;

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('nova-era-venduss-bootstrap', 0));

  if exists (select 1 from public.nev_profiles where user_id = v_user_id) then
    return;
  end if;

  select
    u.email,
    nullif(btrim(coalesce(u.raw_user_meta_data ->> 'full_name', '')), '')
  into v_email, v_full_name
  from auth.users u
  where u.id = v_user_id;

  if v_email is null then
    raise exception 'Não foi possível identificar o e-mail da conta.';
  end if;

  select exists (select 1 from public.nev_profiles) into v_has_profiles;

  if not v_has_profiles then
    select token_hash
    into v_expected_hash
    from nev_private.nev_bootstrap_config
    where singleton = true and used_at is null
    for update;

    if v_expected_hash is null
      or p_bootstrap_token is null
      or pg_catalog.encode(extensions.digest(p_bootstrap_token, 'sha256'), 'hex') <> v_expected_hash then
      raise exception 'Chave inicial inválida.';
    end if;

    insert into public.nev_profiles (user_id, email, full_name, role, active)
    values (v_user_id, lower(v_email), v_full_name, 'admin', true);

    update nev_private.nev_bootstrap_config
    set used_at = now(), used_by = v_user_id
    where singleton = true;
  else
    insert into public.nev_profiles (user_id, email, full_name, role, active)
    values (v_user_id, lower(v_email), v_full_name, 'agent', false);
  end if;
end;
$$;

create or replace function public.nev_admin_set_profile(
  p_user_id uuid,
  p_active boolean,
  p_role text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_current_role text;
  v_current_active boolean;
  v_admin_count integer;
begin
  if not nev_private.nev_is_admin() then
    raise exception 'Apenas administradores podem alterar a equipe.';
  end if;

  if p_role not in ('admin', 'agent') then
    raise exception 'Perfil inválido.';
  end if;

  select role, active
  into v_current_role, v_current_active
  from public.nev_profiles
  where user_id = p_user_id
  for update;

  if not found then
    raise exception 'Usuário não encontrado.';
  end if;

  if v_current_role = 'admin' and v_current_active = true
    and (p_role <> 'admin' or p_active = false) then
    select count(*) into v_admin_count
    from public.nev_profiles
    where role = 'admin' and active = true;

    if v_admin_count <= 1 then
      raise exception 'Mantenha ao menos um administrador ativo.';
    end if;
  end if;

  update public.nev_profiles
  set active = p_active, role = p_role
  where user_id = p_user_id;
end;
$$;

create or replace function public.nev_apply_resolution(
  p_case_id uuid,
  p_resolution_type text,
  p_amount numeric,
  p_notes text,
  p_installments integer default null,
  p_first_due_date date default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_plan_id uuid;
  v_total_cents bigint;
  v_base_cents bigint;
  v_remainder bigint;
  v_installment_cents bigint;
  v_index integer;
begin
  if not nev_private.nev_is_active_staff() then
    raise exception 'Acesso não autorizado.';
  end if;

  if p_resolution_type not in ('store_credit', 'reorder', 'installment_refund', 'other') then
    raise exception 'Tipo de solução inválido.';
  end if;

  if p_amount is null or p_amount < 0 then
    raise exception 'Informe um valor válido.';
  end if;

  if p_resolution_type = 'installment_refund' then
    if p_amount <= 0 then
      raise exception 'O reembolso precisa ter valor maior que zero.';
    end if;
    if p_installments is null or p_installments not between 1 and 36 then
      raise exception 'Informe de 1 a 36 parcelas.';
    end if;
    if p_first_due_date is null then
      raise exception 'Informe a data da primeira parcela.';
    end if;
  end if;

  update public.nev_cases
  set
    status = 'resolved',
    resolution_type = p_resolution_type,
    resolution_amount = round(p_amount, 2),
    resolution_notes = nullif(btrim(coalesce(p_notes, '')), ''),
    resolved_at = now()
  where id = p_case_id;

  if not found then
    raise exception 'Atendimento não encontrado.';
  end if;

  if p_resolution_type = 'installment_refund' then
    if exists (select 1 from public.nev_refund_plans where case_id = p_case_id) then
      raise exception 'Este atendimento já possui um plano de reembolso.';
    end if;

    insert into public.nev_refund_plans (
      case_id, total_amount, installment_count, first_due_date, created_by
    ) values (
      p_case_id, round(p_amount, 2), p_installments, p_first_due_date, auth.uid()
    ) returning id into v_plan_id;

    v_total_cents := round(p_amount * 100)::bigint;
    v_base_cents := v_total_cents / p_installments;
    v_remainder := v_total_cents % p_installments;

    for v_index in 1..p_installments loop
      v_installment_cents := v_base_cents + case when v_index <= v_remainder then 1 else 0 end;

      insert into public.nev_refund_installments (
        refund_plan_id, installment_number, amount, due_date
      ) values (
        v_plan_id,
        v_index,
        v_installment_cents::numeric / 100,
        (p_first_due_date + make_interval(months => v_index - 1))::date
      );
    end loop;
  end if;

  insert into public.nev_case_updates (case_id, author_id, kind, body, metadata)
  values (
    p_case_id,
    auth.uid(),
    'resolution',
    coalesce(nullif(btrim(coalesce(p_notes, '')), ''), 'Solução registrada.'),
    jsonb_build_object('resolution_type', p_resolution_type, 'amount', round(p_amount, 2))
  );
end;
$$;

create or replace function public.nev_mark_installment_paid(
  p_installment_id uuid,
  p_paid boolean,
  p_notes text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_plan_id uuid;
  v_case_id uuid;
  v_number integer;
  v_amount numeric;
begin
  if not nev_private.nev_is_active_staff() then
    raise exception 'Acesso não autorizado.';
  end if;

  select i.refund_plan_id, p.case_id, i.installment_number, i.amount
  into v_plan_id, v_case_id, v_number, v_amount
  from public.nev_refund_installments i
  join public.nev_refund_plans p on p.id = i.refund_plan_id
  where i.id = p_installment_id
  for update of i;

  if not found then
    raise exception 'Parcela não encontrada.';
  end if;

  update public.nev_refund_installments
  set
    status = case when p_paid then 'paid' else 'pending' end,
    paid_at = case when p_paid then now() else null end,
    notes = nullif(btrim(coalesce(p_notes, '')), '')
  where id = p_installment_id;

  update public.nev_refund_plans
  set status = case
    when exists (
      select 1 from public.nev_refund_installments
      where refund_plan_id = v_plan_id and status = 'pending'
    ) then 'open'
    else 'paid'
  end
  where id = v_plan_id;

  insert into public.nev_case_updates (case_id, author_id, kind, body, metadata)
  values (
    v_case_id,
    auth.uid(),
    'payment',
    case when p_paid
      then 'Parcela ' || v_number || ' marcada como paga.'
      else 'Pagamento da parcela ' || v_number || ' desmarcado.'
    end,
    jsonb_build_object('installment_number', v_number, 'amount', v_amount, 'paid', p_paid)
  );
end;
$$;

