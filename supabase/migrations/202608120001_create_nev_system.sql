-- Nova Era Venduss
-- Objetos deste sistema usam o prefixo nev_ para permanecerem isolados.

create schema if not exists nev_private;
revoke all on schema nev_private from public;

create table public.nev_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  full_name text,
  role text not null default 'agent' check (role in ('admin', 'agent')),
  active boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table nev_private.nev_bootstrap_config (
  singleton boolean primary key default true check (singleton),
  token_hash text not null,
  used_at timestamptz,
  used_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

-- Configure o acesso inicial diretamente no banco, por um canal privado.\n-- Não grave o hash do token de ativação em um repositório público.\n
create table public.nev_cases (
  id uuid primary key default gen_random_uuid(),
  case_number bigint generated by default as identity unique,
  customer_name text not null check (char_length(btrim(customer_name)) between 2 and 120),
  whatsapp text not null check (whatsapp ~ '^[0-9]{10,15}$'),
  order_value numeric(12,2) not null default 0 check (order_value >= 0),
  issue_type text not null default 'other' check (
    issue_type in ('thai_order', 'missing_item', 'wrong_item', 'quality', 'refund', 'other')
  ),
  issue_description text not null check (char_length(btrim(issue_description)) between 3 and 4000),
  status text not null default 'open' check (
    status in ('open', 'in_progress', 'waiting_customer', 'resolved', 'cancelled')
  ),
  priority text not null default 'normal' check (
    priority in ('low', 'normal', 'high', 'urgent')
  ),
  assigned_to uuid references public.nev_profiles(user_id) on delete set null,
  created_by uuid not null default auth.uid() references public.nev_profiles(user_id) on delete restrict,
  resolution_type text check (
    resolution_type is null or resolution_type in ('store_credit', 'reorder', 'installment_refund', 'other')
  ),
  resolution_amount numeric(12,2) check (resolution_amount is null or resolution_amount >= 0),
  resolution_notes text,
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.nev_case_updates (
  id uuid primary key default gen_random_uuid(),
  case_id uuid not null references public.nev_cases(id) on delete cascade,
  author_id uuid default auth.uid() references public.nev_profiles(user_id) on delete set null,
  kind text not null default 'note' check (kind in ('note', 'status', 'resolution', 'payment')),
  body text not null check (char_length(btrim(body)) between 1 and 4000),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table public.nev_refund_plans (
  id uuid primary key default gen_random_uuid(),
  case_id uuid not null unique references public.nev_cases(id) on delete cascade,
  total_amount numeric(12,2) not null check (total_amount > 0),
  installment_count integer not null check (installment_count between 1 and 36),
  first_due_date date not null,
  status text not null default 'open' check (status in ('open', 'paid', 'cancelled')),
  created_by uuid not null default auth.uid() references public.nev_profiles(user_id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.nev_refund_installments (
  id uuid primary key default gen_random_uuid(),
  refund_plan_id uuid not null references public.nev_refund_plans(id) on delete cascade,
  installment_number integer not null check (installment_number > 0),
  amount numeric(12,2) not null check (amount > 0),
  due_date date not null,
  status text not null default 'pending' check (status in ('pending', 'paid', 'cancelled')),
  paid_at timestamptz,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (refund_plan_id, installment_number)
);

create index nev_cases_status_idx on public.nev_cases(status);
create index nev_cases_created_at_idx on public.nev_cases(created_at desc);
create index nev_cases_assigned_to_idx on public.nev_cases(assigned_to);
create index nev_case_updates_case_id_idx on public.nev_case_updates(case_id, created_at desc);
create index nev_refund_installments_due_idx on public.nev_refund_installments(status, due_date);

